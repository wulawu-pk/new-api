import { z } from 'zod'

// ============================================================================
// API Key Schema & Types
// ============================================================================

export const apiKeySchema = z.object({
  id: z.number(),
  name: z.string(),
  key: z.string(),
  status: z.number(), // 1: enabled, 2: disabled, 3: expired, 4: exhausted
  remain_quota: z.number(),
  used_quota: z.number(),
  unlimited_quota: z.boolean(),
  expired_time: z.number(), // -1 for never expires
  created_time: z.number(),
  accessed_time: z.number(),
  group: z.string().nullish().default(''),
  auto_groups: z.array(z.string()).nullish().default(null),
  cross_group_retry: z
    .preprocess((v) => {
      if (v === 1) return true
      if (v === 0) return false
      return v
    }, z.boolean())
    .optional()
    .default(false),
  model_limits_enabled: z.boolean(),
  model_limits: z.string().nullish().default(''),
  allow_ips: z.string().nullish().default(''),
  allow_user_quota_query: z.boolean().optional().default(false),
})

export type ApiKey = z.infer<typeof apiKeySchema>

// ============================================================================
// API Request/Response Types
// ============================================================================

export interface ApiResponse<T = unknown> {
  success: boolean
  message?: string
  data?: T
}

export interface GetApiKeysParams {
  p?: number
  size?: number
}

export interface GetApiKeysResponse {
  success: boolean
  message?: string
  data?: {
    items: ApiKey[]
    total: number
    page: number
    page_size: number
  }
}

export interface SearchApiKeysParams {
  keyword?: string
  token?: string
  p?: number
  size?: number
}

export interface ApiKeyFormData {
  name: string
  remain_quota: number
  expired_time: number
  unlimited_quota: boolean
  model_limits_enabled: boolean
  model_limits: string
  allow_ips: string
  allow_user_quota_query: boolean
  group: string
  auto_groups: string[]
  cross_group_retry: boolean
  /** peroai: quota the editor saw; on update an unchanged quota is left alone. */
  expected_remain_quota?: number
  expected_unlimited_quota?: boolean
  /** peroai: one id per create click; repeats return the first key. */
  client_request_id?: string
  /**
   * peroai: the values the editor opened with. The server skips fields the
   * submission leaves equal to these, and writes a changed field only while
   * the stored value still equals it; otherwise nothing is written and it
   * answers `code: "token_conflict"`.
   */
  expected_original?: ApiKeyExpectedOriginal
}

/** Original values of the fields a legacy full edit may change. */
export interface ApiKeyExpectedOriginal {
  name: string
  expired_time: number
  model_limits_enabled: boolean
  model_limits: string
  /** Empty string for none, as the form payload sends it. */
  allow_ips: string | null
  group: string
  cross_group_retry: boolean
  allow_user_quota_query: boolean
}

export interface TokenAutoGroupsConfig {
  groups: string[]
  max_count: number
}

// ============================================================================
// Dialog Types
// ============================================================================

export type ApiKeysDialogType =
  | 'create'
  | 'update'
  | 'delete'
  | 'batch-delete'
  | 'cc-switch'
